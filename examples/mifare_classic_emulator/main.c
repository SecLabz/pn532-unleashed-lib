int main(void)
{
    set_sys_clock_khz(PNU_REQUIRED_SYS_CLOCK_HZ / 1000u, true);
    stdio_init_all();
    puts("Classic 1K demo: UID DEADBEEF, keys A/B FFFFFFFFFFFF.");
    static const card_image_t image = {.model = CARD_CLASSIC_1K,
                                       .uid = memory[0],
                                       .uid_size_bytes = 4,
                                       .memory = &memory[0][0],
                                       .memory_size_bytes = sizeof(memory)};
    nfc_config_t config = nfc_config_default();
    config.transport = PNU_EXAMPLE_TRANSPORT;
    if (nfc_init(&config) != NFC_OK)
    {
        puts(
            "PN532 initialization failed. Check wiring and SPI/HSU selection.");
        (void)nfc_stop();
        while (true)
        {
            tight_loop_contents();
        }
    }
    if (emulation_start(&image) != NFC_OK)
    {
        puts("Classic emulation start failed.");
        (void)nfc_stop();
        while (true)
        {
            tight_loop_contents();
        }
    }
    /* Start validated and copied the image. Reader writes now affect backend
     * RAM only; resetting the MCU reloads the original demonstration image.
     * No serial connection is needed to answer the reader. */
    while (true)
    {
        nfc_poll();
        tight_loop_contents();
    }
}
